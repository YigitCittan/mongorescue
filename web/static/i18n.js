// Current active language code
let currentLang = "en";

// Listeners for language change events
const langChangeCallbacks = [];

const LANG_STORAGE_KEY = "mongorescue_lang";

function readStoredLang() {
  try {
    return window.localStorage.getItem(LANG_STORAGE_KEY) || "";
  } catch (err) {
    return "";
  }
}

function writeStoredLang(lang) {
  try {
    window.localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (err) {
    // storage unavailable: language choice is not persisted
  }
}

/**
 * Initializes language from localStorage or browser preferences.
 */
function initI18n() {
  const saved = readStoredLang();
  if (saved && translations[saved]) {
    currentLang = saved;
  } else {
    const browserLang = (navigator.language || navigator.userLanguage || "en").substring(0, 2).toLowerCase();
    currentLang = translations[browserLang] ? browserLang : "en";
  }

  const langSelect = document.getElementById("lang-select");
  if (langSelect) {
    langSelect.value = currentLang;
    langSelect.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  }

  applyTranslations();
}

/**
 * Sets the active language, updates storage, and triggers re-translation.
 */
function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  writeStoredLang(lang);

  const langSelect = document.getElementById("lang-select");
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }

  applyTranslations();

  // Notify registered callbacks to re-render dynamic content
  langChangeCallbacks.forEach(cb => {
    try { cb(lang); } catch (e) { console.error("i18n callback error:", e); }
  });
}

function lookup(lang, keys) {
  let cur = translations[lang];
  for (const k of keys) {
    if (cur && typeof cur === "object" && cur[k] !== undefined) {
      cur = cur[k];
    } else {
      return undefined;
    }
  }
  return typeof cur === "string" ? cur : undefined;
}

/**
 * Translates a key path using dot notation (e.g. "nav.instant_backup").
 * Falls back to English, then to the given fallback, then to the key itself.
 */
function t(path, fallback = "") {
  const keys = String(path).split(".");
  return lookup(currentLang, keys) || lookup("en", keys) || fallback || path;
}

/**
 * Translates a key and fills {name} placeholders from vars.
 */
function tf(path, vars = {}, fallback = "") {
  return t(path, fallback).replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m);
}

/**
 * Translates all DOM nodes carrying data-i18n (text), data-i18n-placeholder,
 * data-i18n-title and data-i18n-aria-label. Values are always set as text or
 * attributes, never as HTML.
 */
function applyTranslations() {
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });

  const attrs = [
    ["data-i18n-placeholder", "placeholder"],
    ["data-i18n-title", "title"],
    ["data-i18n-aria-label", "aria-label"]
  ];
  attrs.forEach(([dataAttr, target]) => {
    document.querySelectorAll(`[${dataAttr}]`).forEach(el => {
      el.setAttribute(target, t(el.getAttribute(dataAttr)));
    });
  });
}

/**
 * Registers a listener invoked on language change.
 */
function onLanguageChange(callback) {
  langChangeCallbacks.push(callback);
}
